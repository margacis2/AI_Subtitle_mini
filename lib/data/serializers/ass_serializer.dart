import 'dart:ui';
import '../../core/utilities/timestamp_utils.dart';
import '../../domain/entities/subtitle_cue.dart';
import '../../domain/entities/subtitle_style.dart';

class AssSerializer {
  AssSerializer._();

  static String _colorToAss(Color c) {
    // ASS color format: &HAABBGGRR (hex with Alpha Blue Green Red)
    final a = (c.a * 255.0).round().clamp(0, 255).toRadixString(16).padLeft(2, '0').toUpperCase();
    final b = (c.b * 255.0).round().clamp(0, 255).toRadixString(16).padLeft(2, '0').toUpperCase();
    final g = (c.g * 255.0).round().clamp(0, 255).toRadixString(16).padLeft(2, '0').toUpperCase();
    final r = (c.r * 255.0).round().clamp(0, 255).toRadixString(16).padLeft(2, '0').toUpperCase();
    return '&H$a$b$g$r';
  }

  static int _alignmentToAss(SubtitleAlignment align) {
    switch (align) {
      case SubtitleAlignment.bottomLeft:
        return 1;
      case SubtitleAlignment.bottomCenter:
        return 2;
      case SubtitleAlignment.bottomRight:
        return 3;
      case SubtitleAlignment.topCenter:
        return 8;
    }
  }

  /// Serializes a list of SubtitleCues and SubtitleStyle into Advanced SubStation Alpha (.ass).
  static String serialize(List<SubtitleCue> cues, {SubtitleStyle style = const SubtitleStyle()}) {
    final buffer = StringBuffer();

    final primary = _colorToAss(style.textColor);
    final outline = _colorToAss(style.outlineColor);
    final back = _colorToAss(style.backgroundColor);
    final assAlign = _alignmentToAss(style.alignment);
    final bold = style.isBold ? -1 : 0;
    final italic = style.isItalic ? -1 : 0;

    buffer.writeln('[Script Info]');
    buffer.writeln('; Script generated by AI Subtitle Studio');
    buffer.writeln('Title: AI Subtitle Studio Export');
    buffer.writeln('ScriptType: v4.00+');
    buffer.writeln('WrapStyle: 0');
    buffer.writeln('ScaledBorderAndShadow: yes');
    buffer.writeln('PlayResX: 1920');
    buffer.writeln('PlayResY: 1080');
    buffer.writeln();

    buffer.writeln('[V4+ Styles]');
    buffer.writeln('Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding');
    buffer.writeln('Style: Default,${style.fontFamily},${style.fontSize.toInt()},$primary,&H000000FF,$outline,$back,$bold,$italic,0,0,100,100,0,0,1,${style.outlineWidth.toInt()},1,$assAlign,40,40,40,1');
    buffer.writeln();

    buffer.writeln('[Events]');
    buffer.writeln('Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text');

    for (final cue in cues) {
      final startStr = TimestampUtils.formatAss(cue.startMs);
      final endStr = TimestampUtils.formatAss(cue.endMs);
      final safeText = cue.text.replaceAll('\n', '\\N').trim();
      final speaker = cue.speaker ?? '';

      buffer.writeln('Dialogue: 0,$startStr,$endStr,Default,$speaker,0,0,0,,$safeText');
    }

    return buffer.toString();
  }

  /// Parses an ASS file string into a list of SubtitleCue objects.
  static List<SubtitleCue> parse(String content, {String projectId = ''}) {
    final List<SubtitleCue> cues = [];
    final lines = content.replaceAll('\r\n', '\n').replaceAll('\r', '\n').split('\n');

    bool inEvents = false;
    int index = 0;

    for (final line in lines) {
      final trimmed = line.trim();
      if (trimmed.startsWith('[Events]')) {
        inEvents = true;
        continue;
      }
      if (trimmed.startsWith('[') && trimmed.endsWith(']') && !trimmed.startsWith('[Events]')) {
        inEvents = false;
        continue;
      }

      if (inEvents && trimmed.startsWith('Dialogue:')) {
        // Dialogue: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
        final afterColon = trimmed.substring(9).trim();
        final parts = afterColon.split(',');
        if (parts.length >= 10) {
          final startMs = TimestampUtils.parseAss(parts[1]);
          final endMs = TimestampUtils.parseAss(parts[2]);
          final speaker = parts[4].isNotEmpty ? parts[4] : null;
          final text = parts.sublist(9).join(',').replaceAll('\\N', '\n').replaceAll('\\n', '\n').trim();

          index++;
          cues.add(SubtitleCue(
            projectId: projectId,
            cueIndex: index,
            startMs: startMs,
            endMs: endMs,
            text: text,
            speaker: speaker,
          ));
        }
      }
    }

    return cues;
  }
}
